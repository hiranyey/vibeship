import assert from 'node:assert/strict';
import { test } from 'node:test';
import { parseImageRef, pinned } from '../src/docker/image-ref.ts';
import { renderEnvFile, renderImageCompose, toYaml } from '../src/deploy/render.ts';

const DIGEST = `sha256:${'a'.repeat(64)}`;

test('parseImageRef finds the registry host, repository and tag', () => {
  assert.deepEqual(parseImageRef('localhost:5050/library/hello:v1'), { host: 'localhost:5050', repository: 'localhost:5050/library/hello', tag: 'v1' });
  assert.deepEqual(parseImageRef('repoflow.hiranyey.dev/team/app'), { host: 'repoflow.hiranyey.dev', repository: 'repoflow.hiranyey.dev/team/app', tag: 'latest' });
  assert.deepEqual(parseImageRef('localhost/app:1'), { host: 'localhost', repository: 'localhost/app', tag: '1' });
  assert.deepEqual(parseImageRef('nginx:1.29'), { host: null, repository: 'nginx', tag: '1.29' });
  assert.deepEqual(parseImageRef('library/nginx'), { host: null, repository: 'library/nginx', tag: 'latest' });
  assert.throws(() => parseImageRef(`nginx@${DIGEST}`), /digest/);
  assert.equal(pinned('localhost:5050/library/hello:v1', DIGEST), `localhost:5050/library/hello@${DIGEST}`);
});

test('toYaml quotes every string and handles nesting and empty values', () => {
  const yaml = toYaml({ a: 'yes', b: 1, c: true, d: ['x', { e: 'on' }], f: {}, g: [], h: null });
  assert.equal(yaml, [
    'a: "yes"',
    'b: 1',
    'c: true',
    'd:',
    '  - "x"',
    '  -',
    '    e: "on"',
    'f: {}',
    'g: []',
    'h: null',
    '',
  ].join('\n'));
});

test('image projects get one service pinned by digest, on web under their own alias', () => {
  const yaml = renderImageCompose({ name: 'hello', imageRef: 'localhost:5050/library/hello:latest', digest: DIGEST, memLimit: '256m' });
  assert.equal(yaml, [
    '# Generated by Vibeship from its database. Hand edits are overwritten on the next deploy.',
    'name: "hello"',
    'services:',
    '  hello:',
    `    image: "localhost:5050/library/hello@${DIGEST}"`,
    '    container_name: "hello"',
    '    restart: "unless-stopped"',
    '    env_file:',
    '      - ".env"',
    '    volumes:',
    '      - "./data:/data"',
    '    networks:',
    '      web:',
    '        aliases:',
    '          - "hello"',
    '    labels:',
    '      dev.vibeship.project: "hello"',
    '    mem_limit: "256m"',
    'networks:',
    '  web:',
    '    external: true',
    '',
  ].join('\n'));
  assert.doesNotMatch(renderImageCompose({ name: 'x', imageRef: 'x/y', digest: DIGEST, memLimit: null }), /mem_limit/);
});

test('env files double-quote values and escape what compose would interpret', () => {
  const out = renderEnvFile({ B: 'q"uote back\\slash', A: 'plain', C: 'line1\nline2\r', D: 'cost $5 ${HOME}', E: '' });
  assert.equal(out.split('\n').slice(1).join('\n'), [
    'A="plain"',
    'B="q\\"uote back\\\\slash"',
    'C="line1\\nline2\\r"',
    'D="cost \\$5 \\${HOME}"',
    'E=""',
    '',
  ].join('\n'));
});
