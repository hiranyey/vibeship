import { pinned } from '../docker/image-ref.ts';
import { DATA_DIR, DATA_OWNER_LABEL, ENV_FILE, IMAGE_DATA_MOUNT, WEB_NETWORK } from './layout.ts';

export const HEADER = '# Generated by Vibeship from its database. Hand edits are overwritten on the next deploy.\n';

export type Yaml = string | number | boolean | null | Yaml[] | { [key: string]: Yaml };

/**
 * A minimal YAML emitter for the compose files Vibeship generates. Every
 * string is written as a JSON string, which is also a valid YAML scalar, so
 * no value can be misread as a number, boolean or YAML syntax.
 */
export function toYaml(value: Yaml, indent = 0): string {
  const pad = ' '.repeat(indent);
  const scalar = (v: Yaml) => (typeof v === 'string' ? JSON.stringify(v) : String(v));
  // Keys come from user compose files too (env var names, labels), so anything
  // beyond plain identifier characters is quoted.
  const key = (k: string) => (/^[A-Za-z0-9_][A-Za-z0-9_./-]*$/.test(k) ? k : JSON.stringify(k));
  const isBlock = (v: Yaml) => v !== null && typeof v === 'object' && Object.keys(v).length > 0;

  if (Array.isArray(value)) {
    return value
      .map((item) => (isBlock(item) ? `${pad}-\n${toYaml(item, indent + 2)}` : `${pad}- ${scalar(empty(item) ?? item)}\n`))
      .join('');
  }
  if (value !== null && typeof value === 'object') {
    return Object.entries(value)
      .map(([k, v]) => (isBlock(v) ? `${pad}${key(k)}:\n${toYaml(v, indent + 2)}` : `${pad}${key(k)}: ${empty(v) ?? scalar(v)}\n`))
      .join('');
  }
  return `${pad}${scalar(value)}\n`;
}

/** Empty maps and lists must be written inline. */
function empty(v: Yaml): string | null {
  if (Array.isArray(v) && v.length === 0) return '[]';
  if (v !== null && typeof v === 'object' && !Array.isArray(v) && Object.keys(v).length === 0) return '{}';
  return null;
}

export type ImageProjectSpec = {
  name: string;
  imageRef: string;
  digest: string;
  memLimit: string | null;
  /** "<uid>:<gid>"; recorded as a label so changing it shows as a pending change. */
  dataOwner?: string | null;
};

/**
 * The compose file for an image project. The single service and its
 * container are both named after the project, it joins `web` under the
 * `<project>` alias, and `data/` is mounted at `/data` for anything the app
 * needs to keep.
 */
export function renderImageCompose(p: ImageProjectSpec): string {
  const service: Record<string, Yaml> = {
    image: pinned(p.imageRef, p.digest),
    container_name: p.name,
    restart: 'unless-stopped',
    env_file: [ENV_FILE],
    volumes: [`./${DATA_DIR}:${IMAGE_DATA_MOUNT}`],
    networks: { [WEB_NETWORK]: { aliases: [p.name] } },
    labels: { 'dev.vibeship.project': p.name },
  };
  if (p.memLimit) service.mem_limit = p.memLimit;
  // Only a label: the image's own USER still decides who runs. The deploy
  // chowns data/ to this owner before starting the container.
  if (p.dataOwner) (service.labels as Record<string, Yaml>)[DATA_OWNER_LABEL] = p.dataOwner;

  return HEADER + toYaml({
    name: p.name,
    services: { [p.name]: service },
    networks: { [WEB_NETWORK]: { external: true } },
  });
}

/**
 * A `.env` file compose reads exactly: every value is double-quoted, with
 * backslash, quote, dollar (which would otherwise interpolate) and line
 * breaks escaped.
 */
export function renderEnvFile(env: Record<string, string>): string {
  const lines = Object.keys(env)
    .sort()
    .map((key) => {
      const value = env[key]!
        .replaceAll('\\', '\\\\')
        .replaceAll('"', '\\"')
        .replaceAll('$', '\\$')
        .replaceAll('\n', '\\n')
        .replaceAll('\r', '\\r');
      return `${key}="${value}"`;
    });
  return HEADER + lines.map((l) => `${l}\n`).join('');
}
